// Access password (empty = no password)
#define REMOTEXY_ACCESS_PASSWORD ""

// Initialization function - sets up RemoteXY with BLE connection
void initializeRemoteXY() {
  RemoteXYEngine.addGui(RemoteXY_CONF_PROGMEM, &RemoteXY, REMOTEXY_ACCESS_PASSWORD)
    ->addConnection(new CRemoteXYStream_BLEDevice(REMOTEXY_BLUETOOTH_NAME));
}

// Handler function - processes RemoteXY events and communication
void handleRemoteXY() {
  RemoteXYEngine.handler();
}

// Get EEPROM size required by RemoteXY
uint16_t getRemoteXYEEPROMSize() {
  return RemoteXYEngine.getEepromSize();
}

// Initialize RemoteXY EEPROM system (loads saved values)
void initializeRemoteXYEEPROM() {
  RemoteXYEngine.initEeprom();
  Serial.print("[EEPROM] RemoteXY using ");
  Serial.print(RemoteXYEngine.getEepromSize());
  Serial.println(" bytes");
}
